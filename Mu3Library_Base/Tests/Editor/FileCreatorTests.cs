using System;
using System.Text.RegularExpressions;
using Mu3Library.Editor.FileUtil;
using Mu3Library.Editor.Window.Drawer;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.TestTools;

namespace Mu3Library.Tests
{
    public class FileCreatorTests
    {
        private static string Lines(params string[] lines)
        {
            return string.Join(Environment.NewLine, lines) + Environment.NewLine;
        }

        [Test]
        public void WrapInDefineSymbol_KeepsTheGeneratedHeaderOutsideTheCondition()
        {
            string script = Lines(
                "// <auto-generated />",
                "// Generated by a test. Do not edit manually.",
                "using System.Collections.Generic;",
                "",
                "public static class Keys { }");

            string wrapped = FileCreator.WrapInDefineSymbol(script, " TEMPLATE_ADDRESSABLES_SUPPORT ");

            Assert.AreEqual(
                Lines(
                    "// <auto-generated />",
                    "// Generated by a test. Do not edit manually.",
                    "#if TEMPLATE_ADDRESSABLES_SUPPORT",
                    "using System.Collections.Generic;",
                    "",
                    "public static class Keys { }",
                    "#endif"),
                wrapped);
        }

        [Test]
        public void WrapInDefineSymbol_ScriptWithoutHeader_WrapsFromTheFirstLine()
        {
            string wrapped = FileCreator.WrapInDefineSymbol(Lines("public static class Keys { }"), "SYMBOL");

            Assert.AreEqual(Lines("#if SYMBOL", "public static class Keys { }", "#endif"), wrapped);
        }

        [Test]
        public void WrapInDefineSymbol_ScriptWithoutFinalNewLine_EndsTheConditionOnItsOwnLine()
        {
            string wrapped = FileCreator.WrapInDefineSymbol("public static class Keys { }", "SYMBOL");

            Assert.AreEqual(Lines("#if SYMBOL", "public static class Keys { }", "#endif"), wrapped);
        }

        [TestCase(null)]
        [TestCase("")]
        [TestCase("   ")]
        public void WrapInDefineSymbol_WithoutSymbol_ReturnsTheScript(string defineSymbol)
        {
            string script = Lines("// <auto-generated />", "public static class Keys { }");

            Assert.AreEqual(script, FileCreator.WrapInDefineSymbol(script, defineSymbol));
        }

        [TestCase("Packages/com.github.doqltl179.mu3library.base/DrawerLists")]
        [TestCase("Packages\\com.example.readonly")]
        [TestCase("ProjectSettings")]
        [TestCase("AssetsBackup/DrawerLists")]
        public void CreateScriptableObject_FolderOutsideAssets_LogsOneErrorAndReturnsNull(string directory)
        {
            LogAssert.Expect(LogType.Error, new Regex(Regex.Escape($"'{directory}'")));

            DrawerListDrawer created = FileCreator.CreateScriptableObject<DrawerListDrawer>(directory, "List");

            Assert.IsNull(created);
            LogAssert.NoUnexpectedReceived();
        }
    }
}
