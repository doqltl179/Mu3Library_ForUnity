using System;
using System.Text.RegularExpressions;
using Mu3Library.Editor.FileUtil;
using Mu3Library.Editor.Window.Drawer;
using NUnit.Framework;
using UnityEditor;
using UnityEngine;
using UnityEngine.TestTools;

namespace Mu3Library.Tests
{
    public class FileCreatorTests
    {
        /// <summary>
        /// A test that creates assets creates them in a folder under <c>Assets</c> named with this prefix and a unique
        /// suffix. The TearDown deletes it, and the next run deletes any that an interrupted run left.
        /// </summary>
        private const string TempFolderPrefix = nameof(FileCreatorTests) + "_";

        private string _tempFolder;

        [SetUp]
        public void SetUp()
        {
            foreach (string folder in AssetDatabase.GetSubFolders("Assets"))
            {
                if (folder.Substring(folder.LastIndexOf('/') + 1).StartsWith(TempFolderPrefix))
                {
                    AssetDatabase.DeleteAsset(folder);
                }
            }
        }

        [TearDown]
        public void TearDown()
        {
            if (!string.IsNullOrEmpty(_tempFolder))
            {
                AssetDatabase.DeleteAsset(_tempFolder);
            }

            _tempFolder = null;
        }

        private static string Lines(params string[] lines)
        {
            return string.Join(Environment.NewLine, lines) + Environment.NewLine;
        }

        [Test]
        public void WrapInDefineSymbol_KeepsTheGeneratedHeaderOutsideTheCondition()
        {
            string script = Lines(
                "// <auto-generated />",
                "// Generated by a test. Do not edit manually.",
                "using System.Collections.Generic;",
                "",
                "public static class Keys { }");

            string wrapped = FileCreator.WrapInDefineSymbol(script, " TEMPLATE_ADDRESSABLES_SUPPORT ");

            Assert.AreEqual(
                Lines(
                    "// <auto-generated />",
                    "// Generated by a test. Do not edit manually.",
                    "#if TEMPLATE_ADDRESSABLES_SUPPORT",
                    "using System.Collections.Generic;",
                    "",
                    "public static class Keys { }",
                    "#endif"),
                wrapped);
        }

        [Test]
        public void WrapInDefineSymbol_ScriptWithoutHeader_WrapsFromTheFirstLine()
        {
            string wrapped = FileCreator.WrapInDefineSymbol(Lines("public static class Keys { }"), "SYMBOL");

            Assert.AreEqual(Lines("#if SYMBOL", "public static class Keys { }", "#endif"), wrapped);
        }

        [Test]
        public void WrapInDefineSymbol_ScriptWithoutFinalNewLine_EndsTheConditionOnItsOwnLine()
        {
            string wrapped = FileCreator.WrapInDefineSymbol("public static class Keys { }", "SYMBOL");

            Assert.AreEqual(Lines("#if SYMBOL", "public static class Keys { }", "#endif"), wrapped);
        }

        [TestCase(null)]
        [TestCase("")]
        [TestCase("   ")]
        public void WrapInDefineSymbol_WithoutSymbol_ReturnsTheScript(string defineSymbol)
        {
            string script = Lines("// <auto-generated />", "public static class Keys { }");

            Assert.AreEqual(script, FileCreator.WrapInDefineSymbol(script, defineSymbol));
        }

        [TestCase("Packages/com.github.doqltl179.mu3library.base/DrawerLists")]
        [TestCase("Packages\\com.example.readonly")]
        [TestCase("ProjectSettings")]
        [TestCase("AssetsBackup/DrawerLists")]
        public void CreateScriptableObject_FolderOutsideAssets_LogsOneErrorAndReturnsNull(string directory)
        {
            LogAssert.Expect(LogType.Error, new Regex(Regex.Escape($"'{directory}'")));

            DrawerListDrawer created = FileCreator.CreateScriptableObject<DrawerListDrawer>(directory, "List");

            Assert.IsNull(created);
            LogAssert.NoUnexpectedReceived();
        }

        [Test]
        public void CreateScriptableObject_AssetAlreadyAtThePath_ReplacesItAndItsSettings()
        {
            string folder = CreateTempFolder();
            string assetPath = $"{folder}/List.asset";
            DrawerListDrawer existing = ScriptableObject.CreateInstance<DrawerListDrawer>();
            existing.WindowTypeName = typeof(FileCreatorTests).FullName;
            AssetDatabase.CreateAsset(existing, assetPath);

            DrawerListDrawer created = FileCreator.CreateScriptableObject<DrawerListDrawer>(folder, "List");

            Assert.IsTrue(existing == null, "The asset that sat at the path was not destroyed.");
            Assert.IsNotNull(created);
            Assert.AreSame(created, AssetDatabase.LoadAssetAtPath<DrawerListDrawer>(assetPath));
            Assert.AreEqual("", created.WindowTypeName);
            Assert.AreEqual(1, AssetDatabase.FindAssets("", new[] { folder }).Length);
            LogAssert.NoUnexpectedReceived();
        }

        private string CreateTempFolder()
        {
            string name = TempFolderPrefix + Guid.NewGuid().ToString("N").Substring(0, 8);
            _tempFolder = AssetDatabase.GUIDToAssetPath(AssetDatabase.CreateFolder("Assets", name));
            Assert.AreEqual($"Assets/{name}", _tempFolder);

            return _tempFolder;
        }
    }
}
